---@type kanamono.Extra
return {
  ext = ".yml",
  render = function(c, _, name)
    local function color(v, bold)
      return ('      - "%s"'):format(v) .. (bold and '\n      - "bold"' or "")
    end
    local theme = {
      { "activeBorderColor", c.accent, true },
      { "inactiveBorderColor", c.border },
      { "searchingActiveBorderColor", c.yellow, true },
      { "optionsTextColor", c.accent },
      { "selectedLineBgColor", c.surface2 },
      { "inactiveViewSelectedLineBgColor", c.surface1 },
      { "cherryPickedCommitFgColor", c.bg },
      { "cherryPickedCommitBgColor", c.cyan },
      { "markedBaseCommitFgColor", c.bg },
      { "markedBaseCommitBgColor", c.yellow },
      { "unstagedChangesColor", c.git.delete },
      { "defaultFgColor", c.fg },
    }
    local lines = {
      "# " .. name .. " — kanamono.nvim",
      "# Generated by :KanamonoExtras. Do not edit by hand.",
      "# Merge into your config.yml, or load with:",
      "#   LG_CONFIG_FILE=~/.config/lazygit/config.yml,~/.config/lazygit/" .. name .. ".yml",
      "gui:",
      "  theme:",
    }
    for _, t in ipairs(theme) do
      lines[#lines + 1] = "    " .. t[1] .. ":"
      lines[#lines + 1] = color(t[2], t[3])
    end
    lines[#lines + 1] = "  authorColors:"
    lines[#lines + 1] = ('    "*": "%s"'):format(c.fg)
    lines[#lines + 1] = "  branchColors:"
    lines[#lines + 1] = ('    "main": "%s"'):format(c.accent)
    lines[#lines + 1] = ('    "master": "%s"'):format(c.accent)
    return table.concat(lines, "\n") .. "\n"
  end,
}
